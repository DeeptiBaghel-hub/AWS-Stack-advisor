// jsPDF is a genuinely heavy dependency (bundled font metrics etc.), and
// most visitors will never click "export as PDF." Dynamic import (below,
// inside the export function) keeps it out of the main bundle entirely —
// it only downloads for people who actually use the feature, instead of
// taxing every page load. This is also why this is a text-based report
// rather than a pixel-snapshot of the page: canvas-based page capture
// (html2canvas etc.) is fragile across fonts/browsers and prone to layout
// glitches, while a generated text report renders identically everywhere
// and stays real, selectable text rather than an image of text.

function describeDiagram(diagram) {
  const byId = Object.fromEntries((diagram?.nodes || []).map((n) => [n.id, n]));
  const lines = [];
  (diagram?.edges || []).forEach((e) => {
    const from = byId[e.from];
    const to = byId[e.to];
    if (!from || !to) return;
    const arrow = e.optional ? '-.->' : '-->';
    const optionalTag = e.optional ? ' (optional)' : '';
    lines.push(`${from.name} ${arrow} ${to.name}${optionalTag}`);
  });
  return lines;
}

export async function exportRecommendationPdf(recommendation) {
  const { jsPDF } = await import('jspdf');
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const marginX = 48;
  const pageWidth = doc.internal.pageSize.getWidth();
  const contentWidth = pageWidth - marginX * 2;
  let y = 64;

  function ensureSpace(height) {
    if (y + height > doc.internal.pageSize.getHeight() - 56) {
      doc.addPage();
      y = 64;
    }
  }

  function addWrapped(text, fontSize, lineHeight, options = {}) {
    doc.setFontSize(fontSize);
    doc.setFont('helvetica', options.bold ? 'bold' : 'normal');
    const lines = doc.splitTextToSize(text, contentWidth);
    lines.forEach((line) => {
      ensureSpace(lineHeight);
      doc.text(line, marginX, y);
      y += lineHeight;
    });
  }

  // Header
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(120, 120, 120);
  doc.text('STACK ADVISOR — RECOMMENDED ARCHITECTURE', marginX, y);
  y += 28;

  doc.setTextColor(20, 20, 20);
  addWrapped(recommendation.title, 20, 26, { bold: true });
  y += 8;

  // Diagram as text
  const diagramLines = describeDiagram(recommendation.diagram);
  if (diagramLines.length) {
    doc.setTextColor(80, 80, 80);
    addWrapped('ARCHITECTURE', 11, 16, { bold: true });
    doc.setTextColor(40, 40, 40);
    diagramLines.forEach((line) => addWrapped(line, 11, 16));
    y += 10;
  }

  // Why cards
  doc.setTextColor(80, 80, 80);
  addWrapped('RECOMMENDED SERVICES', 11, 16, { bold: true });
  y += 4;
  (recommendation.why || []).forEach((w) => {
    ensureSpace(20);
    doc.setTextColor(20, 20, 20);
    addWrapped(w.name, 13, 18, { bold: true });
    doc.setTextColor(70, 70, 70);
    addWrapped(w.text, 11, 15);
    y += 8;
  });

  // Footnotes
  if (recommendation.footnotes?.length) {
    y += 6;
    doc.setTextColor(80, 80, 80);
    addWrapped('NOTES', 11, 16, { bold: true });
    doc.setTextColor(100, 100, 100);
    recommendation.footnotes.forEach((f) => addWrapped(f, 10, 14));
  }

  // Well-Architected review
  if (recommendation.wellArchitected?.pillars?.length) {
    y += 14;
    doc.setTextColor(80, 80, 80);
    addWrapped(`WELL-ARCHITECTED REVIEW — ${recommendation.wellArchitected.overall}/5 overall`, 11, 16, { bold: true });
    y += 2;
    recommendation.wellArchitected.pillars.forEach((p) => {
      ensureSpace(18);
      doc.setTextColor(20, 20, 20);
      addWrapped(`${p.pillar} — ${p.score}/5`, 12, 16, { bold: true });
      doc.setTextColor(70, 70, 70);
      addWrapped(p.reasoning, 10, 14);
      y += 6;
    });
  }

  // Footer disclaimer
  ensureSpace(40);
  y += 16;
  doc.setDrawColor(220, 220, 220);
  doc.line(marginX, y, pageWidth - marginX, y);
  y += 18;
  doc.setTextColor(140, 140, 140);
  addWrapped(
    'This recommendation is generated by a rule-based engine, not a live AWS pricing or availability check. Treat it as a starting point for an architecture discussion, not a final answer.',
    9,
    12
  );

  const filename = recommendation.title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '')
    .slice(0, 60);

  doc.save(`${filename || 'aws-stack-recommendation'}.pdf`);
}
